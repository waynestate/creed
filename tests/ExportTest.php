<?php

declare(strict_types=1);

namespace Waynestate\Creed\Tests;

use PHPUnit\Framework\Attributes\Test;
use PHPUnit\Framework\TestCase;

/**
 * bin/export.php: the namespace-prefixed copy CREED generates for its
 * consumers (PROCTOR, BOOSTER, ROLLCALL, ADVISOR) to carry under their own
 * namespace, so two tools in one app never fight over a class name.
 */
final class ExportTest extends TestCase
{
    private const NS = 'Waynestate\\Proctor\\Creed';

    /** @var list<string> */
    private array $tmpDirs = [];

    protected function tearDown(): void
    {
        foreach ($this->tmpDirs as $dir) {
            $this->removeDir($dir);
        }
        $this->tmpDirs = [];
    }

    /**
     * A fresh temporary directory, registered for cleanup.
     */
    private function tmpDir(): string
    {
        $dir = sys_get_temp_dir() . '/creed-export-' . uniqid('', true);
        if (!mkdir($dir, 0777, true)) {
            self::fail('Could not create a temporary directory');
        }
        $this->tmpDirs[] = $dir;

        return $dir;
    }

    /**
     * Run PHP with the given arguments.
     *
     * @param list<string> $args
     *
     * @return array{0: int, 1: string, 2: string} exit code, stdout, stderr
     */
    private function runPhp(array $args): array
    {
        $cmd = array_merge([PHP_BINARY], $args);
        $descriptors = [
            0 => ['pipe', 'r'],
            1 => ['pipe', 'w'],
            2 => ['pipe', 'w'],
        ];
        $pipes = [];
        $process = proc_open($cmd, $descriptors, $pipes);
        if (!is_resource($process)) {
            self::fail('Could not start PHP');
        }
        fclose($pipes[0]);
        $stdout = (string) stream_get_contents($pipes[1]);
        $stderr = (string) stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);
        $exit = proc_close($process);

        return [$exit, $stdout, $stderr];
    }

    /**
     * Run bin/export.php with the given arguments.
     *
     * @param list<string> $args
     *
     * @return array{0: int, 1: string, 2: string} exit code, stdout, stderr
     */
    private function runExport(array $args): array
    {
        return $this->runPhp(array_merge([dirname(__DIR__) . '/bin/export.php'], $args));
    }

    /**
     * Export into $dir, failing the test when the export does not exit 0.
     */
    private function exportTo(string $dir): void
    {
        [$exit, , $stderr] = $this->runExport(['--namespace=' . self::NS, '--to=' . $dir]);
        self::assertSame(0, $exit, "export failed: {$stderr}");
    }

    /**
     * Run --check against $dir.
     *
     * @return array{0: int, 1: string, 2: string} exit code, stdout, stderr
     */
    private function check(string $dir): array
    {
        return $this->runExport(['--check', '--namespace=' . self::NS, '--to=' . $dir]);
    }

    #[Test]
    public function exportThenCheckPasses(): void
    {
        $dir = $this->tmpDir();
        $this->exportTo($dir);
        [$exit, , $stderr] = $this->check($dir);
        self::assertSame(0, $exit, "check failed: {$stderr}");
    }

    #[Test]
    public function exportWritesTheFourFiles(): void
    {
        $dir = $this->tmpDir();
        $this->exportTo($dir);
        foreach (['Policy.php', 'State.php', 'policy.json', 'manifest.json'] as $name) {
            self::assertFileExists($dir . '/' . $name);
        }
    }

    #[Test]
    public function namespaceIsRewrittenInBothFiles(): void
    {
        $dir = $this->tmpDir();
        $this->exportTo($dir);
        foreach (['Policy.php', 'State.php'] as $name) {
            $contents = (string) file_get_contents($dir . '/' . $name);
            self::assertStringContainsString('namespace ' . self::NS . ';', $contents, $name);
            self::assertStringNotContainsString('namespace Waynestate\\Creed;', $contents, $name);
        }
    }

    #[Test]
    public function bundledPathIsRepointedAtTheCopy(): void
    {
        $dir = $this->tmpDir();
        $this->exportTo($dir);
        $policy = (string) file_get_contents($dir . '/Policy.php');
        self::assertStringContainsString("__DIR__ . '/policy.json'", $policy);
        self::assertStringNotContainsString("dirname(__DIR__) . '/policy/policy.json'", $policy);
    }

    #[Test]
    public function headerCommentIsFirstLineAfterOpenTag(): void
    {
        $dir = $this->tmpDir();
        $this->exportTo($dir);
        foreach (['Policy.php', 'State.php'] as $name) {
            $contents = (string) file_get_contents($dir . '/' . $name);
            self::assertStringStartsWith(
                "<?php\n// Generated by CREED bin/export.php. Do not edit; re-run the export.\n",
                $contents,
                $name,
            );
        }
    }

    #[Test]
    public function policyJsonIsByteIdentical(): void
    {
        $dir = $this->tmpDir();
        $this->exportTo($dir);
        self::assertSame(
            file_get_contents(dirname(__DIR__) . '/policy/policy.json'),
            file_get_contents($dir . '/policy.json'),
        );
    }

    #[Test]
    public function manifestHasTheExpectedShape(): void
    {
        $dir = $this->tmpDir();
        $this->exportTo($dir);
        $raw = (string) file_get_contents($dir . '/manifest.json');
        self::assertStringEndsWith("\n", $raw, 'the manifest must end with a newline');
        self::assertStringContainsString("\n    ", $raw, 'the manifest must be pretty-printed');

        $manifest = json_decode($raw, true);
        self::assertIsArray($manifest);
        self::assertSame(1, $manifest['schema_version']);
        self::assertSame('creed', $manifest['source']);
        self::assertIsString($manifest['creed_version']);
        self::assertSame(self::NS, $manifest['namespace']);
        self::assertIsArray($manifest['files']);
        foreach (['Policy.php', 'State.php', 'policy.json'] as $name) {
            self::assertArrayHasKey($name, $manifest['files']);
            self::assertSame(
                hash('sha256', (string) file_get_contents($dir . '/' . $name)),
                $manifest['files'][$name]['sha256'],
                $name,
            );
        }
    }

    #[Test]
    public function theCopyIsValidPhp(): void
    {
        $dir = $this->tmpDir();
        $this->exportTo($dir);
        foreach (['Policy.php', 'State.php'] as $name) {
            [$exit, $stdout, $stderr] = $this->runPhp(['-l', $dir . '/' . $name]);
            self::assertSame(0, $exit, "php -l failed for {$name}: {$stdout} {$stderr}");
        }
    }

    #[Test]
    public function theCopyLoadsAndAnswersInASubprocess(): void
    {
        $dir = $this->tmpDir();
        $this->exportTo($dir);

        // A probe that loads the copy under the new namespace and asks for
        // the state of PHP 8.4 on 2026-01-01. PHP 8.4 is active until
        // 2026-12-31, so the answer must be the State, not null.
        $probe = $dir . '/probe.php';
        $script = "<?php\n"
            . 'require ' . var_export($dir . '/Policy.php', true) . ";\n"
            . 'require ' . var_export($dir . '/State.php', true) . ";\n"
            . '$policy = ' . self::NS . '\\Policy::bundled();' . "\n"
            . "\$state = \$policy->tryStateOf('php', '8.4', new DateTimeImmutable('2026-01-01'));\n"
            . "echo \$state === null ? 'null' : \$state->value;\n";
        self::assertNotFalse(file_put_contents($probe, $script));

        [$exit, $stdout, $stderr] = $this->runPhp([$probe]);
        self::assertSame(0, $exit, "probe failed: {$stdout} {$stderr}");
        self::assertSame('active', trim($stdout));
    }

    #[Test]
    public function editingACopiedFileMakesCheckFail(): void
    {
        $dir = $this->tmpDir();
        $this->exportTo($dir);
        $policy = (string) file_get_contents($dir . '/Policy.php');
        self::assertNotFalse(file_put_contents($dir . '/Policy.php', $policy . "// tampered\n"));
        [$exit, , $stderr] = $this->check($dir);
        self::assertSame(1, $exit);
        self::assertStringContainsString('Policy.php', $stderr);
    }

    #[Test]
    public function anExtraFileMakesCheckFail(): void
    {
        $dir = $this->tmpDir();
        $this->exportTo($dir);
        self::assertNotFalse(file_put_contents($dir . '/extra.php', '<?php // not part of the export'));
        [$exit, , $stderr] = $this->check($dir);
        self::assertSame(1, $exit);
        self::assertStringContainsString('extra.php', $stderr);
    }

    #[Test]
    public function aMissingFileMakesCheckFail(): void
    {
        $dir = $this->tmpDir();
        $this->exportTo($dir);
        self::assertTrue(unlink($dir . '/State.php'));
        [$exit, , $stderr] = $this->check($dir);
        self::assertSame(1, $exit);
        self::assertStringContainsString('State.php', $stderr);
    }

    #[Test]
    public function aBadNamespaceExitsTwo(): void
    {
        $dir = $this->tmpDir();
        foreach (['lowercase\\ns', 'Waynestate', '9lives\\ns', 'Waynestate\\lower\\ns'] as $bad) {
            [$exit, , $stderr] = $this->runExport(['--namespace=' . $bad, '--to=' . $dir]);
            self::assertSame(2, $exit, "namespace {$bad} must exit 2");
            self::assertStringContainsString('Usage', $stderr);
        }
    }

    #[Test]
    public function missingOptionsExitTwo(): void
    {
        $dir = $this->tmpDir();
        foreach ([
            [],
            ['--namespace=' . self::NS],
            ['--to=' . $dir],
            ['--check'],
        ] as $args) {
            [$exit, , $stderr] = $this->runExport($args);
            self::assertSame(2, $exit, 'missing options must exit 2');
            self::assertStringContainsString('Usage', $stderr);
        }
    }

    /**
     * Recursively remove a directory tree.
     */
    private function removeDir(string $dir): void
    {
        if (!is_dir($dir)) {
            return;
        }
        $items = scandir($dir) ?: [];
        foreach ($items as $item) {
            if ($item === '.' || $item === '..') {
                continue;
            }
            $path = $dir . '/' . $item;
            if (is_dir($path)) {
                $this->removeDir($path);
            } else {
                unlink($path);
            }
        }
        rmdir($dir);
    }
}
