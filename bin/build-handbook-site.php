<?php

declare(strict_types=1);

/**
 * Builds the handbook pages of the CREED site from handbook/*.md.
 *
 * Usage:
 *   php bin/build-handbook-site.php            write site/handbook/
 *   php bin/build-handbook-site.php --check    fail if site/handbook/ is stale
 *
 * Exit codes:
 *   0  written, or (with --check) every page matches its Markdown
 *   1  (with --check) a page is stale, missing or left over
 *   2  the build itself failed
 *
 * The pages are generated, never hand-edited: a handbook edit without a
 * rebuild turns `composer ci` red. One PHP command, so it runs the same on
 * Windows, macOS and Linux. Like Creed Bratton's alibi, the page is checked
 * against the record every single time; unlike his, it holds.
 */

use Waynestate\Creed\Tools\HandbookSite\SiteBuilder;

require dirname(__DIR__) . '/vendor/autoload.php';

$root = dirname(__DIR__);
$argv = $_SERVER['argv'] ?? [];
$check = in_array('--check', $argv, true);

try {
    $files = (new SiteBuilder($root))->build();
} catch (Throwable $e) {
    fwrite(STDERR, 'Handbook site build failed: ' . $e->getMessage() . "\n");
    exit(2);
}

// Every page this generator wrote before carries its marker; one without a
// matching source any more (a renamed or deleted chapter) is left over.
$marker = 'Generated by bin/build-handbook-site.php';
$leftovers = [];
foreach (glob($root . '/' . SiteBuilder::OUT . '/*') ?: [] as $path) {
    $relative = SiteBuilder::OUT . '/' . basename($path);
    if (isset($files[$relative]) || !is_file($path)) {
        continue;
    }
    $head = (string) file_get_contents($path, false, null, 0, 400);
    if (str_contains($head, $marker)) {
        $leftovers[] = $relative;
    }
}

if ($check) {
    $stale = [];
    foreach ($files as $relative => $content) {
        $path = $root . '/' . $relative;
        $onDisk = is_file($path) ? str_replace("\r\n", "\n", (string) file_get_contents($path)) : null;
        if ($onDisk === null) {
            $stale[] = $relative . ' (missing)';
        } elseif ($onDisk !== $content) {
            $stale[] = $relative . ' (out of date)';
        }
    }
    foreach ($leftovers as $relative) {
        $stale[] = $relative . ' (no longer generated)';
    }
    if ($stale !== []) {
        foreach ($stale as $line) {
            fwrite(STDERR, "stale: {$line}\n");
        }
        fwrite(STDERR, "The handbook site is stale. Run `composer site:handbook` and commit site/handbook/.\n");
        exit(1);
    }
    echo 'Handbook site is current: ' . count($files) . " file(s) match handbook/.\n";
    exit(0);
}

$dir = $root . '/' . SiteBuilder::OUT;
if (!is_dir($dir) && !mkdir($dir, 0o775, true) && !is_dir($dir)) {
    fwrite(STDERR, "Cannot create {$dir}\n");
    exit(2);
}
$written = 0;
foreach ($files as $relative => $content) {
    $path = $root . '/' . $relative;
    $old = is_file($path) ? str_replace("\r\n", "\n", (string) file_get_contents($path)) : null;
    if ($old === $content) {
        continue;
    }
    if (file_put_contents($path, $content) === false) {
        fwrite(STDERR, "Cannot write {$relative}\n");
        exit(2);
    }
    echo "wrote {$relative}\n";
    $written++;
}
foreach ($leftovers as $relative) {
    unlink($root . '/' . $relative);
    echo "removed {$relative}\n";
}
echo "Handbook site built: {$written} file(s) changed, " . count($files) . " in all.\n";
exit(0);
